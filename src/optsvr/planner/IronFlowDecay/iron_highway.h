inline uint8_t get_forbid_mask(int loc) {
    int lo = 0, hi = NUM_CELLS - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (kConstraints[mid].loc == loc) return kConstraints[mid].forbid;
        if (kConstraints[mid].loc < loc) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}

